"""
FoxVC Standalone Native Binary Builder
Compiles any .fox script into a self-contained, standalone native executable using GCC and the native FoxVM C engine.
"""

import os
import subprocess
import tempfile
from engine.lexer import Lexer
from engine.parser import Parser
from engine.bytecode import BytecodeCompiler
from engine.c_vm import FoxCVM


def build_standalone_binary(fox_path: str, output_path: str = None) -> str:
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    if not output_path:
        base = os.path.splitext(os.path.basename(fox_path))[0]
        output_path = os.path.join(os.path.dirname(fox_path) or ".", base)

    with open(fox_path, "r", encoding="utf-8") as f:
        source_code = f.read()

    tokens = Lexer(source_code, filename=fox_path).tokenize()
    ast = Parser(tokens, filename=fox_path).parse()
    pkg = BytecodeCompiler().compile(ast)

    cvm = FoxCVM()
    flat_inst, num_consts, str_consts = cvm.compile_payload(pkg)

    inst_c_str = ", ".join(map(str, flat_inst)) if flat_inst else "0"
    num_c_str = ", ".join(f"{x:.10f}" for x in num_consts) if num_consts else "0.0"

    str_c_entries = []
    for s in str_consts:
        escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
        str_c_entries.append(f'"{escaped}"')
    str_c_str = ", ".join(str_c_entries) if str_c_entries else '""'

    foxvm_c_path = os.path.join(repo_root, "engine", "foxvm.c")

    c_source = f"""// Standalone binary generated by FoxVC AOT Compiler
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "{foxvm_c_path}"

static int g_inst[] = {{{inst_c_str}}};
static double g_num_consts[] = {{{num_c_str}}};
static const char* g_str_consts[] = {{{str_c_str}}};

int main(int argc, char** argv) {{
    int inst_len = {len(flat_inst)};
    int num_len = {len(num_consts)};
    int str_len = {len(str_consts)};
    double res = run_bytecode(g_inst, inst_len, g_num_consts, num_len, g_str_consts, str_len);
    return (int)res;
}}
"""

    with tempfile.NamedTemporaryFile("w", suffix=".c", delete=False) as tmp_c:
        tmp_c.write(c_source)
        tmp_c_path = tmp_c.name

    try:
        include_dir = os.path.join(repo_root, "engine", "include")
        lib_dir = os.path.join(repo_root, "engine", "lib")
        cmd = [
            "gcc", "-O3",
            f"-I{include_dir}",
            tmp_c_path,
            f"-L{lib_dir}",
            "-lraylib",
            f"-Wl,-rpath,{lib_dir}",
            "-lm",
            "-o", output_path
        ]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"GCC Compilation failed: {res.stderr}")
    finally:
        if os.path.exists(tmp_c_path):
            os.remove(tmp_c_path)

    return os.path.abspath(output_path)
